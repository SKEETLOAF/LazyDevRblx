import { BriefInputError, normalizeProjectBrief } from './briefs.mjs';

// A portable project brief, not a credential, permission grant, or an agent
// instruction to read project files. Session reference IDs are never portable.
export const PROJECT_MANIFEST_SCHEMA = 'lazydev.project.v1';
const isObject = x => x !== null && typeof x === 'object' && !Array.isArray(x);
const allowedKeys = (obj, keys) => isObject(obj) && Object.keys(obj).every(x => keys.includes(x));

function fail(message) { throw new BriefInputError(message); }

function inputFields(brief) {
  return {
    projectName: brief.projectName,
    ...(brief.creativeDirection == null ? {} : { creativeDirection: brief.creativeDirection }),
    style: brief.style,
    preserve: brief.preserve,
    avoid: brief.avoid,
    constraints: brief.constraints,
    // Source provenance labels in a live brief are generated by LAZY, not
    // trusted from a manifest. Only user-declared fields travel to disk.
    sourceLinks: (brief.sourceLinks ?? []).map(link => ({
      title: link.title,
      url: link.url,
      kind: link.kind,
      rightsClaim: link.rightsClaim ?? 'unknown',
      ...(link.note == null ? {} : { note: link.note }),
    })),
  };
}

function normalizedFields(input) {
  const validated = normalizeProjectBrief(input);
  return inputFields(validated);
}

export function makeProjectManifest(brief) {
  if (!isObject(brief)) fail('Expected a project brief');
  const ids = brief.referenceIds ?? [];
  if (!Array.isArray(ids) || ids.length > 8) fail('Invalid session reference list');
  const portable = normalizedFields(inputFields(brief));
  return {
    schema: PROJECT_MANIFEST_SCHEMA,
    brief: portable,
    omittedSessionReferenceCount: ids.length,
  };
}

export function parseProjectManifest(value) {
  if (!allowedKeys(value, ['schema', 'brief', 'omittedSessionReferenceCount']) ||
      value.schema !== PROJECT_MANIFEST_SCHEMA) {
    fail('Unsupported or invalid project manifest schema');
  }
  const count = value.omittedSessionReferenceCount;
  if (!Number.isInteger(count) || count < 0 || count > 8) {
    fail('Invalid omittedSessionReferenceCount');
  }
  if (!allowedKeys(value.brief, [
    'projectName', 'creativeDirection', 'style', 'preserve', 'avoid',
    'constraints', 'sourceLinks',
  ])) {
    fail('Unexpected portable project brief fields');
  }
  // This revalidates URL restrictions, rights claims, style and bounded text.
  // It cannot resurrect an image/GIF from an earlier daemon session.
  return { brief: normalizedFields(value.brief), omittedSessionReferenceCount: count };
}
